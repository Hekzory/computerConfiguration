"""Real hook protocol checks; no Codex, account, network or third-party Python deps."""
import json
from pathlib import Path
import shlex
import subprocess
import sys
import tomllib
import unittest

ROOT = Path(__file__).resolve().parents[1]
ROLE = ROOT / "roles/codex"
GIT = ROLE / "files/git-guard.sh"
SSH = ROOT / "user_home/.claude/hooks/ssh-fish-guard.py"


class Hooks(unittest.TestCase):
    def run_hook(self, script, command, tool="Bash"):
        interpreter = ["bash"] if script.suffix == ".sh" else [sys.executable, "-S"]
        result = subprocess.run(
            [*interpreter, str(script)],
            input=json.dumps({"hook_event_name": "PreToolUse", "tool_name": tool,
                              "tool_input": {"command": command}, "cwd": str(ROOT)}),
            text=True, capture_output=True, timeout=5, check=True,
        )
        self.assertEqual(result.stderr, "")
        if not result.stdout:
            return None
        output = json.loads(result.stdout)["hookSpecificOutput"]
        self.assertEqual(output["hookEventName"], "PreToolUse")
        self.assertEqual(output["permissionDecision"], "deny")
        self.assertTrue(output["permissionDecisionReason"])
        return output

    def test_attribution_is_denied(self):
        for attribution in (
            "Co-Authored-By: Codex <codex@openai.com>",
            "co-authored-by: Claude <noreply@anthropic.com>",
            "Generated with Codex", "Generated by OpenAI", "Generated using ChatGPT",
            "Generated with Claude Code", "noreply@openai.com", "🤖",
        ):
            for git in ("git", "/usr/bin/git", "git -C '/tmp/a b'", "git -c commit.gpgsign=false"):
                with self.subTest(attribution=attribution, git=git):
                    self.assertIsNotNone(self.run_hook(GIT, f"{git} commit -m {shlex.quote(attribution)}"))

    def test_clean_commands_are_silent(self):
        for command in (
            "git commit -m 'Fix Codex router'", "git commit --amend -m 'Fix OpenAI API auth'",
            "git commit --amend --no-edit", "git status", "git log --format='%b'",
            "git add . && git commit -m 'Fix bug'", "printf '%s' 'Co-Authored-By: Codex'",
            "git status; echo 'commit Generated with Codex'",
        ):
            with self.subTest(command=command):
                self.assertIsNone(self.run_hook(GIT, command))

    def test_multiline_and_chained_commit(self):
        for command in (
            "git add . && git commit -m 'Fix bug\n\nCo-Authored-By: Codex'",
            "git commit -m \"$(cat <<'MSG'\nFix parser's bug\nGenerated with Codex\nMSG\n)\"",
        ):
            with self.subTest(command=command):
                self.assertIsNotNone(self.run_hook(GIT, command))

    def test_non_shell_tools_are_ignored(self):
        for script in (GIT, SSH):
            self.assertIsNone(self.run_hook(script, "git commit -m 'Generated with Codex'", tool="Read"))

    def test_ssh_bash_syntax_is_denied(self):
        for command in (
            "ssh host 'x=1; echo $x'",
            "ssh -p 2222 host 'for i in 1 2; do echo $i; done'",
            "timeout 30 ssh host 'if true; then echo ok; fi'",
            "ssh host <<'SCRIPT'\necho hello\nSCRIPT",
            "ssh host 'echo ${HOME}'",
        ):
            with self.subTest(command=command):
                self.assertIsNotNone(self.run_hook(SSH, command))

    def test_ssh_explicit_shell_and_simple_commands_are_allowed(self):
        for command in (
            "ssh host uptime", "ssh host 'ls -la'", "ssh host bash -c 'x=1; echo $x'",
            "ssh host bash -s <<'SCRIPT'\nx=1\necho $x\nSCRIPT",
            "ssh -p 2222 host /usr/bin/bash -s", "grep ssh script.sh",
        ):
            with self.subTest(command=command):
                self.assertIsNone(self.run_hook(SSH, command))


class Configuration(unittest.TestCase):
    def test_configuration_scope_and_hook_wiring(self):
        config = tomllib.loads((ROLE / "files/config.toml").read_text())
        self.assertEqual(set(config), {
            "project_doc_fallback_filenames", "allow_login_shell", "shell_environment_policy",
            "sandbox_mode", "approval_policy", "approvals_reviewer", "sandbox_workspace_write",
            "features", "tui", "hooks", "memories",
            "model_reasoning_effort", "plan_mode_reasoning_effort",
        })
        self.assertEqual(config["sandbox_mode"], "workspace-write")
        self.assertEqual(config["approval_policy"], "on-request")
        self.assertEqual(config["approvals_reviewer"], "user")
        self.assertEqual(config["sandbox_workspace_write"], {"network_access": True})
        self.assertEqual(config["model_reasoning_effort"], "high")
        self.assertEqual(config["plan_mode_reasoning_effort"], "high")
        self.assertEqual(config["project_doc_fallback_filenames"], ["CLAUDE.md", "claude.md"])
        self.assertEqual(config["features"], {
            "hooks": True, "shell_snapshot": False, "memories": True,
        })
        self.assertEqual(config["memories"], {
            "version": "v2",
            "generate_memories": True,
            "use_memories": True,
            "extract_model": "gpt-6.1-sol",
            "consolidation_model": "gpt-6.1-sol",
        })
        self.assertEqual(config["tui"]["status_line"], [
            "model-with-reasoning", "context-used", "context-window-size", "current-dir",
            "weekly-limit", "git-branch",
        ])
        self.assertEqual(set(config["hooks"]), {"PreToolUse"})
        groups = config["hooks"]["PreToolUse"]
        self.assertEqual(len(groups), 2)
        self.assertEqual(groups[0]["matcher"], "^Bash$")
        self.assertEqual(len(groups[0]["hooks"]), 2)
        for handler, interpreter, source in zip(
            groups[0]["hooks"], ("/usr/bin/bash", "/usr/bin/python3"), (GIT, SSH)
        ):
            self.assertEqual(handler["type"], "command")
            self.assertEqual(handler["timeout"], 10)
            self.assertNotIn("async", handler)
            self.assertEqual(shlex.split(handler["command"]), [
                interpreter, f"/etc/codex/hooks/{source.name}",
            ])
            self.assertTrue(source.is_file())
        self.assertEqual(groups[1], {
            "matcher": "^mcp__cua_repl__js$",
            "hooks": [{
                "type": "command",
                "command": "/usr/bin/python3 /etc/codex/hooks/browser-connect.py",
                "timeout": 25,
                "statusMessage": "Checking Desktop browser connection",
            }],
        })
        tasks = (ROLE / "tasks/main.yml").read_text()
        self.assertIn("src: browser-connect.py", tasks)
        self.assertIn("dest: /etc/codex/hooks/browser-connect.py", tasks)
        self.assertLess(tasks.index("src: browser-connect.py"), tasks.index("src: config.toml"))

    def test_ownership_marker(self):
        self.assertTrue((ROLE / "files/config.toml").read_text().startswith(
            "# Managed by computerConfiguration: Codex\n"))

    def test_existing_ssh_guard_is_reused_without_removing_anything(self):
        tasks = (ROLE / "tasks/main.yml").read_text()
        self.assertIn("{{ role_path }}/../../user_home/.claude/hooks/ssh-fish-guard.py", tasks)
        self.assertNotIn("state: absent", tasks)
        self.assertNotIn("dest: ~/.codex", tasks)

    def test_shell_syntax(self):
        subprocess.run(["bash", "-n", str(GIT)], check=True, timeout=5)


if __name__ == "__main__":
    unittest.main()
